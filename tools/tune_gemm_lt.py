#!/usr/bin/env python3
"""Offline tool: build InfiniCore's hipBLASLt choice table from autotune logs.

Run a workload once with INFINICORE_GEMM_LT_AUTOTUNE=1 (and the Lt GEMM path,
INFINICORE_HYGON_GEMM=lt); InfiniCore then times every heuristic candidate on
the first call of each GEMM shape and prints

    [infinicore.gemm_lt] <device> <ops> m n k batch lda ldb ldc = <i>  # 0:1.234 1:fail 2:1.100(nondet) ...

This script merges such lines (several ranks / runs may report the same
shape), keeps candidates that were reproducible in every report, picks the
lowest mean time, and writes the table read through INFINICORE_GEMM_LT_TABLE.
Shapes whose best candidate is not at least --min-gain faster than candidate 0
are left out (they keep the library's first choice).
"""
import argparse
import collections
import re
import statistics
from pathlib import Path

LINE = re.compile(r"\[infinicore\.gemm_lt\] (?P<key>.+?) = (?P<index>-?\d+)\s+#(?P<report>.*)$")


def parse(paths):
    reports = collections.defaultdict(list)
    for path in paths:
        for line in Path(path).read_text(errors="replace").splitlines():
            match = LINE.search(line)
            if not match:
                continue
            times = {}
            for item in match.group("report").split():
                index, _, value = item.partition(":")
                if value == "fail" or value.endswith("(nondet)"):
                    times[int(index)] = None
                else:
                    times[int(index)] = float(value)
            reports[match.group("key")].append(times)
    return reports


def choose(runs):
    indices = set.intersection(*(set(times) for times in runs))
    usable = {i: statistics.mean(times[i] for times in runs) for i in indices
              if all(times[i] is not None for times in runs)}
    return usable


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("logs", nargs="+", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--min-gain", type=float, default=0.02, help="relative gain over candidate 0 (default 2%%)")
    args = parser.parse_args()
    lines = ["# InfiniCore hipBLASLt candidate choices (INFINICORE_GEMM_LT_TABLE); generated by",
             "# tools/tune_gemm_lt.py from INFINICORE_GEMM_LT_AUTOTUNE=1 logs. Format:",
             "# <device> <ops> m n k batch lda ldb ldc = <heuristic index>  # timings"]
    total_before = total_after = 0.0
    for key, runs in sorted(parse(args.logs).items()):
        usable = choose(runs)
        if 0 not in usable:
            print(f"skip (candidate 0 not reproducible or failed): {key}")
            continue
        best = min(usable, key=usable.get)
        base = usable[0]
        gain = (base - usable[best]) / base
        status = "use" if best != 0 and gain >= args.min_gain else "keep 0"
        print(f"{key}: candidate 0 {base:.3f} ms, best {best} {usable[best]:.3f} ms ({gain:+.1%}) "
              f"from {len(runs)} report(s) -> {status}")
        if status == "use":
            lines.append(f"{key} = {best}  # {base:.3f} -> {usable[best]:.3f} ms ({gain:.1%}), {len(runs)} report(s)")
            total_before += base
            total_after += usable[best]
    args.output.write_text("\n".join(lines) + "\n")
    if total_before:
        print(f"tuned shapes: {total_before:.3f} -> {total_after:.3f} ms per call set")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
